"""Generate and verify dependency projections from their owning manifests.

pyproject.toml owns LLM requirements; Hub and the pinned external host keep
their own declarations. The Linux test lock is generated data, not a second
place to choose versions. No plugin is imported or installed by this tool.
"""

import argparse
import ast
import hashlib
from importlib.metadata import PackageNotFoundError, version
import json
from pathlib import Path
import re
import subprocess
import tomllib


ROOT = Path(__file__).resolve().parents[2]
LOCK = ROOT / "tests/llm/dependencies-linux.lock"
PLATFORM = "x86_64-unknown-linux-gnu"


def metadata(path):
    tree = ast.parse(path.read_text(encoding="utf-8"))
    node = next(n.value for n in tree.body if isinstance(n, ast.Assign)
                and any(isinstance(t, ast.Name) and t.id == "PLUGIN_META" for t in n.targets))
    return ast.literal_eval(node), node


def declarations(root=ROOT):
    config = tomllib.loads((root / "pyproject.toml").read_text())
    project, plugin = config["project"], config["tool"]["ish-llm"]["plugin"]
    requirements = list(project["dependencies"])
    for name in plugin["extras"]:
        requirements.extend(project["optional-dependencies"][name])
    imports = plugin["imports"]
    projected = []
    for requirement in requirements:
        name = re.match(r"[\w.-]+", requirement)[0].lower().replace("_", "-")
        projected.append(requirement + ("|" + imports[name] if name in imports else ""))
    return project, projected


def lock_inputs(root=ROOT):
    project, projected = declarations(root)
    host = root / "ish.platform"
    host_project = tomllib.loads((host / "pyproject.toml").read_text())["project"]
    hub, _ = metadata(root / "hub/hub.py")
    return {
        "python": project["requires-python"],
        "platform": PLATFORM,
        "host_revision": subprocess.check_output(
            ["git", "-C", str(host), "rev-parse", "HEAD"], text=True).strip(),
        "requirements": sorted(set(
            [spec.split("|", 1)[0] for spec in projected + hub["dependencies"]]
            + host_project["dependencies"])),
    }


def fingerprint(inputs):
    return hashlib.sha256(json.dumps(inputs, sort_keys=True).encode()).hexdigest()


def write_plugin(root=ROOT):
    path = root / "llm/llm.py"
    _, projected = declarations(root)
    _, node = metadata(path)
    dependencies = next(value for key, value in zip(node.keys, node.values)
                        if isinstance(key, ast.Constant) and key.value == "dependencies")
    lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
    start, end = dependencies.lineno - 1, dependencies.end_lineno - 1
    replacement = "[\n" + "".join(f"        {json.dumps(spec)},\n" for spec in projected) + "    ]"
    lines[start:end + 1] = [lines[start][:dependencies.col_offset] + replacement
                            + lines[end][dependencies.end_col_offset:]]
    path.write_text("".join(lines), encoding="utf-8")


def write_lock(uv):
    inputs = lock_inputs()
    result = subprocess.run([
        uv, "pip", "compile", "-", "--python-version", inputs["python"].removeprefix("=="),
        "--python-platform", inputs["platform"], "--generate-hashes",
        "--no-header", "--no-annotate",
    ], input="\n".join(inputs["requirements"]), text=True, capture_output=True, check=True)
    LOCK.write_text(
        "# Generated by python -m tests.llm.dependencies --lock\n"
        f"# inputs-sha256: {fingerprint(inputs)}\n" + result.stdout, encoding="utf-8")


def check(root=ROOT, *, installed=False):
    errors = []
    _, projected = declarations(root)
    actual, _ = metadata(root / "llm/llm.py")
    if actual["dependencies"] != projected:
        errors.append("PLUGIN_META dependencies differ from pyproject.toml; regenerate --write-plugin")
    lock = (root / "tests/llm/dependencies-linux.lock").read_text()
    if f"# inputs-sha256: {fingerprint(lock_inputs(root))}\n" not in lock:
        errors.append("test lock inputs changed; review and regenerate --lock")
    if installed:
        from packaging.requirements import Requirement
        pins = re.findall(r"^([\w.-]+)==([^\s\\]+)", lock, re.MULTILINE)
        if not pins:
            errors.append("test lock contains no exact distribution pins")
        for name, wanted in pins:
            try:
                actual = version(name)
            except PackageNotFoundError:
                actual = None
            if actual != wanted:
                errors.append(f"{name}: installed {actual!r}, lock requires {wanted}")
        for spec in lock_inputs(root)["requirements"]:
            requirement = Requirement(spec)
            try:
                actual = version(requirement.name)
            except PackageNotFoundError:
                continue  # The exact-pin check already reports missing distributions.
            if not requirement.specifier.contains(actual):
                errors.append(f"{requirement.name}: installed {actual!r}, declaration requires {spec}")
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write-plugin", action="store_true")
    mode.add_argument("--lock", action="store_true")
    parser.add_argument("--uv", default="uv")
    parser.add_argument("--installed", action="store_true")
    args = parser.parse_args()
    if args.write_plugin:
        write_plugin()
    elif args.lock:
        write_lock(args.uv)
    else:
        errors = check(installed=args.installed)
        print(json.dumps({"errors": errors}, ensure_ascii=False, indent=2))
        return int(bool(errors))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
