    """Open lookup naming rules; unknown keys keep Language's existing fallback."""

    STATUS_PREFIX = 'status_'
    RECOVERY_RESULT_PREFIX = 'recovery_result_'
    RAG_PHASE_PREFIX = 'rag_phase_'
    RAG_UNIT_PREFIX = 'rag_unit_'
    GENERAL_PREFIX = 'general_'
    GENERAL_CATEGORY_PREFIX = 'general_category_'
    HISTORY_PREFIX = 'history_'
    RECOVERY_PREFIX = 'recovery_'
    ACTIVITY_PROVIDER_PREFIX = 'activity_provider_'
    COMPONENT_ACTION_PREFIX = 'component_action_'
    SHORTCUT_PREFIX = 'shortcut_'
    SETTINGS_PREFIX = 'settings_'
    SETTINGS_THEME_PREFIX = 'settings_theme_'
    SETTINGS_DESCRIPTION_PREFIX = 'settings_desc_'
    SETTINGS_GROUP_PREFIX = 'settings_group_'
    FAILURE_PREFIX = 'failure_'
    COMMAND_PREFIX = 'command_'
    COMPONENT_TITLE_SUFFIX = '_title'
